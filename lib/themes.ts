const GRAY_PALETTE_FROM_BACKGROUND_RE = /--color-([a-z]+)-/;

const grayPaletteFromBackground = (background: string) =>
  GRAY_PALETTE_FROM_BACKGROUND_RE.exec(background)?.[1];

const grayCodeTokens = (palette: string, mode: "light" | "dark") => {
  const mix = mode === "light" ? `${palette}-950` : `${palette}-50`;

  return {
    code: `color-mix(in srgb, var(--background) 99%, var(--color-${mix}))`,
    "code-highlight": `color-mix(in srgb, var(--color-${mix}) 4%, var(--code))`,
  };
};

const formatCssVarsBlock = (
  selector: string,
  vars: Record<string, string | undefined>
) => {
  const lines = Object.entries(vars)
    .filter((entry): entry is [string, string] => entry[1] !== undefined)
    .map(([key, value]) => `  --${key}: ${value};`);

  return `${selector} {\n${lines.join("\n")}\n}`;
};

export const createCssVars = (
  primaryCss: PrimaryColor["cssVars"],
  grayCss: GrayColor["cssVars"],
  radiusCss: BorderRadius["cssVars"]
) => {
  const palette = grayPaletteFromBackground(grayCss.light.background);
  const lightCode = palette ? grayCodeTokens(palette, "light") : {};
  const darkCode = palette ? grayCodeTokens(palette, "dark") : {};

  return `${formatCssVarsBlock(":root", {
    ...grayCss.light,
    ...lightCode,
    ...STATUS_LIGHT,
    ...primaryCss.light,
    ...radiusCss,
  })}\n\n${formatCssVarsBlock(".dark", {
    ...grayCss.dark,
    ...darkCode,
    ...STATUS_DARK,
    ...primaryCss.dark,
    ...radiusCss,
  })}`;
};
